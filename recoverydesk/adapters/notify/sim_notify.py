"""SimNotifyAdapter — deterministic offline notification rail (SIM zone).

Sends always "deliver"; the WORLD decides whether the customer responds (the
response event is generated by the sim outcome engine at wake time, keyed by
the same idem key — probabilities first, outcomes after).
"""
from __future__ import annotations

from sqlalchemy.orm import Session

from adapters.payments.port import DeliveryResult


class SimNotifyAdapter:
    def __init__(self, session: Session):
        self._s = session

    def send(self, *, channel: str, template_id: str, locale: str, slots: dict,
             idem_key: str, at) -> DeliveryResult:
        return DeliveryResult(
            delivery_ref=f"simn-{idem_key[:12]}", accepted=True, channel=channel
        )
